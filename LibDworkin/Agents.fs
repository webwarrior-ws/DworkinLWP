let performAction (action : DworkinAgent -> unit) (agent : Agent) : unit =
    match agent with
    | :? DworkinAgent as dworkinAgent -> action dworkinAgent |> ignore
    | :? DelayAgent as delayAgent -> 
        let oldAction = delayAgent.Action
        delayAgent.Action <- 
            fun env -> 
                match oldAction env with
                | Some(:? DworkinAgent as a) -> 
                    action a
                    Some(a :> Agent)
                | _ -> None
    | _ -> failwith "Unsupported agent type"
    

type DworkinAgent(config: DworkinAgentConfig, randomSeed : int) =
    inherit MovingAgent()
    (* #paint *)
    let mutable speed = Nullable<float32>()
    let mutable curvature = Nullable<float32>()
    let mutable thickness = Nullable<float32>()
    let mutable flipFactor = 1.0f
    // readonly (initailized once, then only read):
    let mutable brush : Brush = null
    let mutable attributes : Attributes = null
    let mutable parent : DworkinAgent option = None
    
    let mutable random = Random(randomSeed)

    member val ThicknessFactor = 1.0f with get, set
    member val LengthFactor : float32 = 1.0f with get, set
    member val Generation = 1 with get, set
    member val GenerationLimit = 50 with get, set
    member val NoCollisions = false with get, set
    member val Collision : Collision option = None with get, set
    
    member this.Random = random
    member this.FlipFactor = flipFactor
    member this.Config = config
    member this.Attributes : Attributes = 
        if isNull attributes then
            attributes <- Attributes(this.DworkinEnvironment.AttributesStore, this.Id)
        attributes

    member this.Curvature = 
        if not curvature.HasValue then
            curvature <- Nullable(config.Curvature.Evaluate(this) * this.FlipFactor / this.LengthFactor)
        curvature.Value
    
    member this.Thickness = 
        if not thickness.HasValue then
            thickness <- Nullable(config.Thickness.Evaluate(this) * this.ThicknessFactor)
        thickness.Value
    
    override this.Speed
        with get() : float32 = 
            if not speed.HasValue then
               speed <- Nullable(config.Speed.Evaluate(this) * this.LengthFactor)
            speed.Value
        and set(aNumber : float32) =
            speed <- Nullable(aNumber * this.LengthFactor)
        
    member this.Parent 
        with get() = parent
        and set(value : DworkinAgent option) = 
            parent <- value
            match parent with
            | Some(p) -> this.Generation <- p.Generation + 1
            | None -> ()

    override this.DistanceCovered =
        base.DistanceCovered / this.LengthFactor
    
    member this.Brush =
        if isNull brush then
            brush <- config.Brush.GetBrushFor(this)
        brush

    member this.TotalDistance =
        config.TotalDistance
    
    member inline this.S = this.DistanceCovered
    
    member this.T =
        min (this.DistanceCovered / this.TotalDistance) 1.0f
    
    member this.RelativeThickness =
        this.Thickness / this.ThicknessFactor

    member this.IsFlipped =
        flipFactor < 0.0f
    
    member this.Flip() =
        flipFactor <- -flipFactor
    
    member this.DworkinEnvironment : DworkinEnvironment =
        this.Environment.Value :?> DworkinEnvironment

    member this.BranchMarks =
        // manually inlined GetOrSetIfAbsent for performance
        let accessor = this.Attributes.BranchMarks
        match accessor.GetValue() with
        | ValueSome(marks) -> marks
        | ValueNone -> 
            let marks = SmallDictionary<int, BranchMarkList>.Create()
            accessor.Set(marks)
            marks
    
    member this.TotalNumBranches =
        this.BranchMarks.Values |> Seq.sumBy (fun x -> x.Length)

    member this.AddBranchMarkFor(aMark, tag) =
        (getOrSetIfAbsent this.BranchMarks tag BranchMarkList).Add(aMark)

    member this.Branch(anAgentConfig, options) =
        this.Branch(anAgentConfig, options, ignore)

    member this.Branch(anAgentConfig, options : BranchOptions, agentBlock) =
        if this.Generation < this.GenerationLimit then
            options.Parent <- Some(this.Copy())
            options.Config <- Some(anAgentConfig)
            let agent = this.SpawnUsingOptions(options) 
            agent |> performAction agentBlock 
            this.AddBranchMarkFor(BranchMark(this.DistanceCovered), options.Tag)
    
    member this.LastBranchMark =
        let marks = this.BranchMarks
        if marks.Length = 0 then
            let lst = BranchMarkList()
            marks.[0] <- lst
            lst.Last
        else
            Seq.maxBy (fun mark -> mark.S) (marks.Values |> Seq.map (fun s -> s.Last))

    member this.LastBranchMarkFor(tag) =
        (getOrSetIfAbsent this.BranchMarks tag BranchMarkList).Last

    member this.NumBranchesFor(tag) =
        this.BranchMarks.GetTransformed(tag, (fun marks -> marks.Length), fun () -> 0)

    member this.Copy() : DworkinAgent =
        let copy = this.MemberwiseClone() :?> DworkinAgent
        copy.PostCopy()
        copy
    
    member this.PostCopy() =
        brush <- null
    
    member this.GetFootprint() : IDworkinAgentState =
        DworkinAgentFootprint(this) :> IDworkinAgentState

    member this.ResetCache() =
        speed <- Nullable()
        curvature <- Nullable()
        thickness <- Nullable()
        this.Collision <- None

    member this.ScaleBy(s : Point) =
        this.ThicknessFactor <- this.ThicknessFactor * s.X
        this.LengthFactor <- this.LengthFactor * s.Y
    
    member this.ScaleBy(num : float32) =
        this.ScaleBy(Point(num))

    member this.SetScale(factor) =
        this.ThicknessFactor <- factor
        this.LengthFactor <- factor

    member this.Spawn(anAgentConfig : DworkinAgentConfig, options) =
        this.Spawn(anAgentConfig, options, ignore)

    member this.Spawn(anAgentConfig, options : AgentSpawnOptions, agentBlock) =
        if this.Generation < this.GenerationLimit then
            options.Parent <- Some(this.Copy())
            options.Config <- Some(anAgentConfig)
            let agent = this.SpawnUsingOptions(options)
            agent |> performAction agentBlock

    member this.SpawnShape(shape : Shape, options : ShapeSpawnOptions) =
        options.Parent <- Some(this.Copy())
        options.Shape <- shape
        this.DworkinEnvironment.AddShape(options.TransformedShape, options.TransformedPaint)
    
    member this.SpawnUsingOptions(options : AgentSpawnOptions) : Agent =
        match options.Seed with 
        | Some(_) -> () 
        | None -> options.Seed <- Some(this.Random.Next())
        this.DworkinEnvironment.SpawnUsingOptions(options)
    
    /// perform agent rotation and movement
    member this.MoveAndRotate() =
        let rotation = this.Curvature * this.Speed
        base.Step()
        this.Direction <- this.Direction.Rotate(rotation)

    override this.Step() =
        if this.Age = 0 && not this.NoCollisions 
           && (match config.TerminationConditions.Collision with | Some(x) -> x.Evaluate(this) | None -> false) then
            this.Delete()
        else
            this.Brush.Evaluate(this)
            if not this.NoCollisions then 
                config.ColliderOptions.Evaluate(this)
            if config.TerminationConditions.AnySatisfy(this) then
                this.Terminate()
            else
                this.MoveAndRotate()
                config.Branching.Evaluate(this)
                this.ResetCache()

    member this.Terminate() =
        config.Termination.Evaluate(this)
        this.Delete()
    
    interface IEquatable<IUnique> with
        override this.Equals(other) =
            this.Id = other.Id

    interface IDworkinAgentState with
        member this.DistanceCovered = this.DistanceCovered
        member this.GetFootprint() = this.GetFootprint()
        member this.Id = this.Id
        member this.LengthFactor = this.LengthFactor
        member this.Position = this.Position
        member this.Thickness = this.Thickness
        member this.ThicknessFactor = this.ThicknessFactor
        member this.Direction = this.Direction
        member this.Parent = this.Parent |> Option.map (fun p -> p :> IDworkinAgentState)

   
type DworkinAgentFootprint(agent : DworkinAgent) =
    let position = agent.Position
    let direction = agent.Direction
    let distanceCovered = agent.DistanceCovered
    let mutable id = 0
    
    member this.Id 
        with get() = if id = 0 then agent.Id else id
        and set(value : int) = id <- value
    
    member this.Config = agent.Config
    member this.DworkinEnvironment = agent.DworkinEnvironment

    interface IDworkinAgentState with
        member this.DistanceCovered = distanceCovered
        member this.GetFootprint() = this :> IDworkinAgentState
        member this.LengthFactor = agent.ThicknessFactor
        member this.Position = position
        member this.Thickness =
            let s = distanceCovered * DworkinAgentFormula.Factor
            let t = min (distanceCovered / agent.TotalDistance) 1.0f
            agent.Config.Thickness.Evaluate(s, t) * agent.ThicknessFactor
        member this.ThicknessFactor = agent.ThicknessFactor
        member this.Id = this.Id
        member this.Direction = direction
        member this.Parent = agent.Parent |> Option.map (fun p -> p :> IDworkinAgentState)
    
    interface IEquatable<IUnique> with
        override this.Equals(other) =
            (this :> IUnique).Id = other.Id
    
    override this.Equals(other) =
        match other with
        | :? IUnique as otherAgent -> (this :> IUnique).Id = otherAgent.Id
        | _ -> false
    override this.GetHashCode() = hash (this :> IUnique).Id


type DworkinEnvironment(bounds, randomSeed : int) =
    inherit Environment(bounds)
    let mutable numDelayAgents = 0
    let initialQuadTreeBounds = Rectangle.FromTLRB(bounds.Top - 10.0f, bounds.Left - 10.0f, bounds.Right + 15.0f, bounds.Bottom + 15.0f)
    let colliders : System.Collections.Generic.IDictionary<CollisionLayer, QuadTree<Collider>> = SmallDictionary.Create()
    let mutable shapes = ResizeArray<struct (Shape * ShapePaint)>()
    let mutable random = Random(randomSeed)
    do 
        random.Next() |> ignore
    
    member val AttributesStore = AttributesStore()
    
    override this.Random = random

    override this.Delay(action , numSteps) =
        this.AddAgent(FixedDelayAgent(numSteps, Action=action))
    
    override this.HasActiveAgents =
        this.AgentsCount - numDelayAgents > 0
    
    override this.Paint = OpenTK.Graphics.Color4.White // ?? is it needed?

    override this.Step() =
        this.StepAgents()
        let result = shapes.ToArray()
        shapes.Clear()
        result

    override this.AddAgent(agent) =
        base.AddAgent(agent) 
        if agent :? DelayAgent then
            numDelayAgents <- numDelayAgents + 1
    
    override this.RemoveAgent(agent) =
        let oldCount = this.AgentsCount
        let result = base.RemoveAgent(agent)
        if result && (agent :? DelayAgent) then
            numDelayAgents <- numDelayAgents - (oldCount - this.AgentsCount)
        result
    
    member this.AddCollider(aCollider) =
        this.AddColliderToLayer(aCollider, CollisionLayer.Default)

    member this.AddColliderToLayer(aCollider, layer) =
        let tree = getOrSetIfAbsent colliders layer (fun () -> QuadTree(initialQuadTreeBounds))
        try
            tree.Insert(aCollider)
        with
        | :? OutOfBounds as ex ->
#if __ANDROID__       
            Android.Util.Log.Error("Dworkin", sprintf "collider (%A) out of bounds (%A)" ex.objBounds ex.treeBounds)
            |> ignore
#else
            ()
#endif
    
    /// Apply predicate to all colliders within given rect on given layers.
    /// Stop when predicate returns true or all colliders are processed.
    /// If all colliders are processed but predicate never returned true, return false
    member this.QueryColliders(rect : Rectangle, layers: CollisionLayers, predicate : CollisionLayer -> Collider -> bool) =
        (colliders :?> SmallDictionary<_, _>).Exists(fun layer tree -> layers.Contains layer && tree.Query(rect, predicate layer))
    
    /// Return true if given collider collides with any colliders in given layers
    member this.TestForCollision(layers: CollisionLayers, collider : Collider) : bool =
        this.QueryColliders((collider :> IHasBounds).Bounds, layers, fun layer c -> collide collider c)
    
    member this.RemoveColliderLayer(layer : CollisionLayer) =
        colliders.Remove(layer) |> ignore
    
    // spawning
    member this.Spawn(agentConfig, options) =
        this.Spawn(agentConfig, options, ignore)

    member this.Spawn(agentConfig, options : AgentSpawnOptions, agentBlock) =
        options.Config <- Some(agentConfig)
        let agent = this.SpawnUsingOptions(options)
        agent |> performAction agentBlock
        agent

    member this.SpawnUsingOptions(options : AgentSpawnOptions) : Agent =
        let seed = match options.Seed with | Some(value) -> value | None -> this.Random.Next()
        let agent = DworkinAgent(options.Config.Value, seed, Position=options.Position, Direction=options.Direction)
        match options.Parent with
        | Some(parent) -> 
            agent.Parent <- options.Parent
            agent.ThicknessFactor <- parent.ThicknessFactor
            agent.LengthFactor <- parent.LengthFactor
            agent.GenerationLimit <- parent.GenerationLimit
            if parent.IsFlipped then
                agent.Flip()
        | None -> ()
        agent.Environment <- Some(this :> Environment)
        let addedAgent : Agent = 
            match options.Delay with
            | Some(delayAgent) -> 
                delayAgent.Action <- (fun env -> env.AddAgent(agent); Some(agent :> Agent))
                delayAgent :> Agent
            | None -> agent :> Agent
        this.AddAgent(addedAgent)
        addedAgent

    // shapes
    member this.AddShape(shape : Shape, fillType: ShapePaint) =
        shapes.Add(struct (shape, fillType))

    member this.SpawnShape(shape : Shape, options : ShapeSpawnOptions) =
        options.Shape <- shape
        this.AddShape(options.TransformedShape, options.TransformedPaint)
    